    struct NamedEventLayout {
        enum class FieldType : uint8_t { F32, F64, I32, U32, I64, U64, Bool, Vec2, Vec3, Vec4, Quat, Color };
        struct Field {
            std::string name;
            FieldType type = FieldType::F32;
            uint32_t offset = 0;
        };
        uint32_t size = 0;
        std::vector<Field> fields;
    };


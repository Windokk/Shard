namespace Shard::Engine::Events {

    struct Event {
        virtual ~Event() = default;
        Core::ObjectID sourceObjectID;
        explicit Event(Core::ObjectID source) : sourceObjectID(source) {}
    };

    // Common Event Definitions
    // Input events : sent globally, from the Input phase, as the OS reports them (see TranslateInputEvent). They carry no
    // source object (ObjectID(0)). The state read through IInput is already up to date when a handler runs.

    /// keyCode is an Input::Key. repeated : the press generated by the OS key repeat, not a new one.
    struct KeyPressedEvent : public Event {
        int keyCode;
        bool repeated;
        KeyPressedEvent(const int key, const bool rep, Core::ObjectID source) : Event(source), keyCode(key), repeated(rep) {}
        Input::Key key() const { return static_cast<Input::Key>(keyCode); }
    };

    struct KeyReleasedEvent : public Event {
        int keyCode;
        KeyReleasedEvent(const int key, Core::ObjectID source) : Event(source), keyCode(key) {}
        Input::Key key() const { return static_cast<Input::Key>(keyCode); }
    };

    /// Characters typed (UTF-8), keyboard layout and modifiers applied : for text fields, not for gameplay bindings.
    struct TextInputEvent : public Event {
        std::string text;
        TextInputEvent(std::string t, Core::ObjectID source) : Event(source), text(std::move(t)) {}
    };

    struct MouseButtonPressedEvent : public Event {
        Input::MouseButton button;
        float x, y;     // in the window, pixels
        MouseButtonPressedEvent(Input::MouseButton b, float px, float py, Core::ObjectID source) : Event(source), button(b), x(px), y(py) {}
    };

    struct MouseButtonReleasedEvent : public Event {
        Input::MouseButton button;
        float x, y;
        MouseButtonReleasedEvent(Input::MouseButton b, float px, float py, Core::ObjectID source) : Event(source), button(b), x(px), y(py) {}
    };

    struct MouseMovedEvent : public Event {
        float x, y;         // position in the window
        float deltaX, deltaY;   // relative motion (still reported while the cursor is captured)
        MouseMovedEvent(float px, float py, float dx, float dy, Core::ObjectID source) : Event(source), x(px), y(py), deltaX(dx), deltaY(dy) {}
    };

    struct MouseScrolledEvent : public Event {
        float deltaX, deltaY;
        MouseScrolledEvent(float dx, float dy, Core::ObjectID source) : Event(source), deltaX(dx), deltaY(dy) {}
    };

    /// deviceId identifies the pad while it stays plugged in (the same id as the OS event).
    struct GamepadConnectedEvent : public Event {
        uint32_t deviceId;
        GamepadConnectedEvent(uint32_t id, Core::ObjectID source) : Event(source), deviceId(id) {}
    };

    struct GamepadDisconnectedEvent : public Event {
        uint32_t deviceId;
        GamepadDisconnectedEvent(uint32_t id, Core::ObjectID source) : Event(source), deviceId(id) {}
    };

    struct GamepadButtonPressedEvent : public Event {
        uint32_t deviceId;
        Input::GamepadButton button;
        GamepadButtonPressedEvent(uint32_t id, Input::GamepadButton b, Core::ObjectID source) : Event(source), deviceId(id), button(b) {}
    };

    struct GamepadButtonReleasedEvent : public Event {
        uint32_t deviceId;
        Input::GamepadButton button;
        GamepadButtonReleasedEvent(uint32_t id, Input::GamepadButton b, Core::ObjectID source) : Event(source), deviceId(id), button(b) {}
    };

    /// Every change of an axis, raw (no dead zone, sticks -1..1, triggers 0..1) : use IInput::GetGamepadAxis for a polled, dead-zoned value.
    struct GamepadAxisEvent : public Event {
        uint32_t deviceId;
        Input::GamepadAxis axis;
        float value;
        GamepadAxisEvent(uint32_t id, Input::GamepadAxis a, float v, Core::ObjectID source) : Event(source), deviceId(id), axis(a), value(v) {}
    };

    enum WorldChangeType{
        DESTROYED,
        CREATED,
        MOVED,
        ACTIVATED,
        DEACTIVATED,
        LOADED,
        UNLOADED
    };

    struct WorldStructureChangedEvent : public Event{
        const int worldAssetID;
        const WorldChangeType changeType;
        const std::string actorName;
        WorldStructureChangedEvent(
        const int& worldAssetID, const WorldChangeType changeType, const std::string actorName, Core::ObjectID source) : Event(source), worldAssetID(worldAssetID), changeType(changeType), actorName(actorName) {}
    };

    class EventDispatcher;

    /// @brief Turns an OS input event (key, text, mouse, gamepad) into the matching engine event and emits it globally.
    /// Anything that is not an input event (window, drop, quit...) is ignored.
    /// @return true if an event was emitted
    bool TranslateInputEvent(const Core::Platform::OSEvent& event, EventDispatcher& dispatcher);

    // EventDispatcher
    class EventDispatcher {
        public:

            using ComponentID = uint32_t;

            // Subscriptions
            template<typename T>
            void subscribeGlobal(std::function<void(const T&)> callback) {
                globalSubscribers[typeid(T)].emplace_back([cb = std::move(callback)](const Event& e) {
                    cb(static_cast<const T&>(e));
                });
            }

            template<typename T>
            void subscribeToWorld(int worldID, std::function<void(const T&)> callback) {
                worldSubscribers[worldID][typeid(T)].emplace_back([cb = std::move(callback)](const Event& e) {
                    cb(static_cast<const T&>(e));
                });
            }

            template<typename T>
            void subscribeToActor(Core::ObjectID actorID, std::function<void(const T&)> callback) {
                actorSubscribers[actorID][typeid(T)].emplace_back([cb = std::move(callback)](const Event& e) {
                    cb(static_cast<const T&>(e));
                });
            }

            template<typename T>
            void subscribeToComponent(ComponentID componentID, std::function<void(const T&)> callback) {
                componentSubscribers[componentID][typeid(T)].emplace_back(
                    [cb = std::move(callback)](const Event& e) {
                        cb(static_cast<const T&>(e));
                    }
                );
            }

            // Emission
            template<typename T>
            void emitGlobal(const T& event) {
                dispatchTo(globalSubscribers, event);
            }

            template<typename T>
            void emitToWorld(int worldID, const T& event) {
                auto it = worldSubscribers.find(worldID);
                if (it != worldSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

            template<typename T>
            void emitToActor(Core::ObjectID actorID, const T& event) {
                auto it = actorSubscribers.find(actorID);
                if (it != actorSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

            template<typename T>
            void emitToComponent(ComponentID componentID, const T& event) {
                auto it = componentSubscribers.find(componentID);
                if (it != componentSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

                
        private:

            using Handler = std::function<void(const Event&)>;
            using SubscriberMap = std::unordered_map<std::type_index, std::vector<Handler>>;

            template<typename T>
            void dispatchTo(SubscriberMap& map, const T& event) {
                auto it = map.find(typeid(T));
                if (it != map.end()) {
                    for (auto& handler : it->second) {
                        handler(event);
                    }
                }
            }

            // Subscriber storage
            SubscriberMap globalSubscribers;
            std::unordered_map<int, SubscriberMap> worldSubscribers;
            std::unordered_map<Core::ObjectID, SubscriberMap> actorSubscribers;
            std::unordered_map<ComponentID, SubscriberMap> componentSubscribers;
    };
}
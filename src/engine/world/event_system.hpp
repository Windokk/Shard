    class EventDispatcher {
        public:

            using ComponentID = uint32_t;

            using Subscription = uint64_t;

            using Owner = uint32_t;

            template<typename T>
            Subscription subscribeGlobal(std::function<void(const T&)> callback, Owner owner = 0) {
                return Add(globalSubscribers[typeid(T)], std::move(callback), owner);
            }

            template<typename T>
            Subscription subscribeToWorld(int worldID, std::function<void(const T&)> callback, Owner owner = 0) {
                return Add(worldSubscribers[worldID][typeid(T)], std::move(callback), owner);
            }

            template<typename T>
            Subscription subscribeToActor(Core::ObjectID actorID, std::function<void(const T&)> callback, Owner owner = 0) {
                return Add(actorSubscribers[actorID][typeid(T)], std::move(callback), owner);
            }

            template<typename T>
            Subscription subscribeToComponent(ComponentID componentID, std::function<void(const T&)> callback, Owner owner = 0) {
                return Add(componentSubscribers[componentID][typeid(T)], std::move(callback), owner);
            }

            Subscription subscribeNamed(const std::string& name, std::function<void(const NamedEvent&)> callback, Owner owner = 0) {
                return Add(namedGlobal[name], std::move(callback), owner);
            }

            Subscription subscribeNamedToWorld(int worldID, const std::string& name, std::function<void(const NamedEvent&)> callback, Owner owner = 0) {
                return Add(namedWorld[worldID][name], std::move(callback), owner);
            }

            void emitNamed(const std::string& name, const void* payload, size_t size) {
                auto it = namedGlobal.find(name);
                if (it != namedGlobal.end()) DispatchList(it->second, NamedEvent(name, payload, size, Core::ObjectID(0)));
            }

            void emitNamedToWorld(int worldID, const std::string& name, const void* payload, size_t size) {
                auto world = namedWorld.find(worldID);
                if (world == namedWorld.end()) return;
                auto it = world->second.find(name);
                if (it != world->second.end()) DispatchList(it->second, NamedEvent(name, payload, size, Core::ObjectID(0)));
            }

            // Safe from inside a handler: it is skipped from then on and swept after the outermost emit.
            bool Unsubscribe(Subscription token) {
                bool found = false;
                ForEachList([&](HandlerList& list) {
                    for (auto& h : list)
                        if (h.token == token && h.alive) { h.alive = false; found = true; m_Dirty = true; }
                });
                if (found) SweepIfIdle();
                return found;
            }

            bool describeNamed(const std::string& name, NamedEventLayout layout, Owner owner = 0) {
                auto it = namedLayouts.find(name);
                if (it != namedLayouts.end() && it->second.second != owner) return false;
                namedLayouts[name] = { std::move(layout), owner };
                return true;
            }

            const NamedEventLayout* namedLayout(const std::string& name) const {
                auto it = namedLayouts.find(name);
                return it == namedLayouts.end() ? nullptr : &it->second.first;
            }

            std::vector<std::string> describedNames() const {
                std::vector<std::string> names;
                for (const auto& kv : namedLayouts) names.push_back(kv.first);
                std::sort(names.begin(), names.end());
                return names;
            }

            size_t UnsubscribeOwner(Owner owner) {
                if (owner == 0) return 0;
                for (auto it = namedLayouts.begin(); it != namedLayouts.end();) {
                    if (it->second.second == owner) it = namedLayouts.erase(it);
                    else ++it;
                }
                size_t count = 0;
                ForEachList([&](HandlerList& list) {
                    for (auto& h : list)
                        if (h.owner == owner && h.alive) { h.alive = false; ++count; m_Dirty = true; }
                });
                if (count) SweepIfIdle();
                return count;
            }

            template<typename T>
            void emitGlobal(const T& event) {
                dispatchTo(globalSubscribers, event);
            }

            template<typename T>
            void emitToWorld(int worldID, const T& event) {
                auto it = worldSubscribers.find(worldID);
                if (it != worldSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

            template<typename T>
            void emitToActor(Core::ObjectID actorID, const T& event) {
                auto it = actorSubscribers.find(actorID);
                if (it != actorSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

            template<typename T>
            void emitToComponent(ComponentID componentID, const T& event) {
                auto it = componentSubscribers.find(componentID);
                if (it != componentSubscribers.end()) {
                    dispatchTo(it->second, event);
                }
            }

        private:

            using Handler = std::function<void(const Event&)>;
            struct Entry {
                Subscription token = 0;
                Owner owner = 0;
                bool alive = true;
                Handler fn;
            };
            using HandlerList = std::vector<Entry>;
            using SubscriberMap = std::unordered_map<std::type_index, HandlerList>;

            template<typename T>
            Subscription Add(HandlerList& list, std::function<void(const T&)> callback, Owner owner) {
                Entry entry;
                entry.token = ++m_NextToken;
                entry.owner = owner;
                entry.fn = [cb = std::move(callback)](const Event& e) { cb(static_cast<const T&>(e)); };
                list.push_back(std::move(entry));
                return list.back().token;
            }

            template<typename T>
            void dispatchTo(SubscriberMap& map, const T& event) {
                auto it = map.find(typeid(T));
                if (it == map.end()) return;
                DispatchList(it->second, event);
            }

            void DispatchList(HandlerList& list, const Event& event) {
                // Depth must go back down even if a handler throws, or nothing is ever swept again.
                struct DepthGuard {
                    EventDispatcher& d;
                    explicit DepthGuard(EventDispatcher& dispatcher) : d(dispatcher) { ++d.m_EmitDepth; }
                    ~DepthGuard() { --d.m_EmitDepth; }
                };
                {
                    DepthGuard guard(*this);
                    // By index: a handler may subscribe to the same type and move the list's storage.
                    for (size_t i = 0; i < list.size(); ++i) {
                        if (!list[i].alive) continue;
                        Handler fn = list[i].fn;
                        fn(event);
                    }
                }
                SweepIfIdle();
            }

            template<typename F>
            void ForEachList(F&& fn) {
                auto visit = [&](SubscriberMap& m) { for (auto& kv : m) fn(kv.second); };
                visit(globalSubscribers);
                for (auto& kv : worldSubscribers) visit(kv.second);
                for (auto& kv : actorSubscribers) visit(kv.second);
                for (auto& kv : componentSubscribers) visit(kv.second);
                for (auto& kv : namedGlobal) fn(kv.second);
                for (auto& world : namedWorld) for (auto& kv : world.second) fn(kv.second);
            }

            template<typename Map, typename Pred>
            static void EraseIf(Map& map, Pred&& empty) {
                for (auto it = map.begin(); it != map.end();) {
                    if (empty(it->second)) it = map.erase(it);
                    else ++it;
                }
            }

            void SweepIfIdle() {
                if (m_EmitDepth != 0 || !m_Dirty) return;
                ForEachList([](HandlerList& list) {
                    list.erase(std::remove_if(list.begin(), list.end(), [](const Entry& e) { return !e.alive; }), list.end());
                });
                auto emptyList = [](const HandlerList& list) { return list.empty(); };
                auto prune = [&](SubscriberMap& map) { EraseIf(map, emptyList); return map.empty(); };
                prune(globalSubscribers);
                EraseIf(worldSubscribers, prune);
                EraseIf(actorSubscribers, prune);
                EraseIf(componentSubscribers, prune);
                EraseIf(namedGlobal, emptyList);
                EraseIf(namedWorld, [&](std::unordered_map<std::string, HandlerList>& names) { EraseIf(names, emptyList); return names.empty(); });
                m_Dirty = false;
            }

            SubscriberMap globalSubscribers;
            std::unordered_map<int, SubscriberMap> worldSubscribers;
            std::unordered_map<Core::ObjectID, SubscriberMap> actorSubscribers;
            std::unordered_map<ComponentID, SubscriberMap> componentSubscribers;
            std::unordered_map<std::string, HandlerList> namedGlobal;
            std::unordered_map<std::string, std::pair<NamedEventLayout, Owner>> namedLayouts;
            std::unordered_map<int, std::unordered_map<std::string, HandlerList>> namedWorld;

            Subscription m_NextToken = 0;
            int m_EmitDepth = 0;
            bool m_Dirty = false;
    };
